export function fillAdminCopy(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{([a-zA-Z]+)\}/g, (full, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : full)
}
